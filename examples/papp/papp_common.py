"""Shared build helper for the e3d example PAPPs.

Each example's build.py calls build(). It uses the PAPP SDK of an
ESP32_P4_Launcher checkout: ../ESP32_P4_Launcher next to this repository, or
the folder in the PAPP_LAUNCHER environment variable. Output goes to
build/<name>/<name>.papp at the repository root.
"""
import os
import sys

PAPP_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(PAPP_DIR))
ENGINE = os.path.join(ROOT, "e3d")
LAUNCHER = os.environ.get("PAPP_LAUNCHER", os.path.join(os.path.dirname(ROOT), "ESP32_P4_Launcher"))
SDK_TOOLS = os.path.join(LAUNCHER, "papp-sdk", "tools")


def _sdk():
    if not os.path.isfile(os.path.join(SDK_TOOLS, "papp_build.py")):
        sys.exit(f"build: no PAPP SDK at {LAUNCHER} (set PAPP_LAUNCHER)")
    sys.path.insert(0, SDK_TOOLS)
    import papp_build  # noqa: E402
    return papp_build


def embed_text(out_dir, files):
    """{c_name: path} -> one C file with const char <c_name>[] holding each text file."""
    gen = os.path.join(out_dir, "gen")
    os.makedirs(gen, exist_ok=True)
    lines = ["/* generated by the example's build.py */"]
    for cname, path in files.items():
        text = open(path, encoding="ascii").read()
        lines.append(f"const char {cname}[] =")
        for row in text.replace("\r", "").split("\n"):
            lines.append('    "' + row.strip().replace("\\", "\\\\").replace('"', '\\"') + '\\n"')
        lines[-1] += ";"
    path = os.path.join(gen, "assets.c")
    data = "\n".join(lines) + "\n"
    if not os.path.isfile(path) or open(path, encoding="ascii").read() != data:
        open(path, "w", encoding="ascii").write(data)
    return path


def build(name, here, sources, embed=None, includes=()):
    """name: the PAPP name; here: the example's folder (icon.png, version.txt);
    sources: the example's own C files; embed: {c_name: text file} to embed;
    includes: more include folders."""
    papp_build = _sdk()
    out = os.path.join(ROOT, "build", name)
    src = [os.path.join(here, s) for s in sources]
    src += [os.path.join(ENGINE, "src", "e3d.c"), os.path.join(ENGINE, "src", "e3d_render.c")]
    if embed:
        src.append(embed_text(out, embed))
    # the renderer uses the P4's PIE (128-bit integer SIMD)
    pie = {os.path.join(ENGINE, "src", "e3d_render.c"): ["-march=rv32imafc_zicsr_zifencei_xesppie"]}
    has_icon = os.path.isfile(os.path.join(here, "icon.png"))
    has_version = os.path.isfile(os.path.join(here, "version.txt"))
    papp_build.build(name, src, includes=[os.path.join(ENGINE, "include"), os.path.join(ENGINE, "src")] + list(includes),
                     libc=True, out_dir=out,
                     app_cflags=["-O2", "-Wextra", "-Wno-unused-parameter"], per_file_cflags=pie,
                     icon_dir=here if has_icon else None, version_dir=here if has_version else None)
    return os.path.join(out, name + ".papp")
