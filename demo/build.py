#!/usr/bin/env python3
"""3D Engine demo PAPP.

    python demo/build.py        -> build/e3d_demo/e3d_demo.papp

Uses the PAPP SDK of an ESP32_P4_Launcher checkout: ../ESP32_P4_Launcher next to
this project, or the folder in the PAPP_LAUNCHER environment variable. The
object files from ReferenceCode/ are embedded as C strings (build/e3d_demo/gen).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LAUNCHER = os.environ.get("PAPP_LAUNCHER", os.path.join(os.path.dirname(ROOT), "ESP32_P4_Launcher"))
SDK_TOOLS = os.path.join(LAUNCHER, "papp-sdk", "tools")
if not os.path.isfile(os.path.join(SDK_TOOLS, "papp_build.py")):
    sys.exit(f"build: no PAPP SDK at {LAUNCHER} (set PAPP_LAUNCHER)")
sys.path.insert(0, SDK_TOOLS)
import papp_build  # noqa: E402

ASSETS = ["letters3d", "numbers3d", "marvell3d", "motorola3d"]
OUT = os.path.join(ROOT, "build", "e3d_demo")


def gen_assets():
    """ReferenceCode/<name>.txt -> const char asset_<name>[] in one C file."""
    gen = os.path.join(OUT, "gen")
    os.makedirs(gen, exist_ok=True)
    lines = ["/* generated by demo/build.py from the ReferenceCode object files */"]
    for name in ASSETS:
        text = open(os.path.join(ROOT, "ReferenceCode", name + ".txt"), encoding="ascii").read()
        lines.append(f"const char asset_{name}[] =")
        for row in text.replace("\r", "").split("\n"):
            lines.append('    "' + row.strip().replace("\\", "\\\\").replace('"', '\\"') + '\\n"')
        lines[-1] += ";"
    path = os.path.join(gen, "assets.c")
    data = "\n".join(lines) + "\n"
    if not os.path.isfile(path) or open(path, encoding="ascii").read() != data:
        open(path, "w", encoding="ascii").write(data)
    return path


def main():
    engine = os.path.join(ROOT, "engine")
    sources = [os.path.join(HERE, "main.c"), os.path.join(engine, "e3d.c"),
               os.path.join(engine, "e3d_render.c"), gen_assets()]
    # the renderer may use the P4's PIE (128-bit integer SIMD) for block fills and copies
    pie = {os.path.join(engine, "e3d_render.c"): ["-march=rv32imafc_zicsr_zifencei_xesppie"]}
    papp_build.build("e3d_demo", sources, includes=[engine], libc=True, out_dir=OUT,
                     app_cflags=["-O2", "-Wextra", "-Wno-unused-parameter"], per_file_cflags=pie,
                     icon_dir=HERE, version_dir=HERE)


if __name__ == "__main__":
    main()
